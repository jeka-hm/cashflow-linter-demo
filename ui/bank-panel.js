'use strict';
const fs = require('fs');
const path = require('path');
const DIR = path.join(__dirname, 'bank-panel');
const parts = fs.readdirSync(DIR).filter(f => /^\d+.*\.part\.js$/.test(f)).sort();
module._compile(parts.map(f => fs.readFileSync(path.join(DIR, f), 'utf8')).join(''), __filename);
